function drawText(buf, text, x, y, size) {
  for (let row = 0; row < 13; row++) {
    const rowBits = FONT[text[row]];
    if (!rowBits) continue;
    for (let col = 0; col < 9; col++) {
      if (rowBits[col]) {
        const px = x + col * size;
        const py = y + row * size;
        const idx = (py * 600 + px) * 4;
        buf[idx] = 255; buf[idx + 1] = 255; buf[idx + 2] = 255; buf[idx + 3] = 255;
      }
    }
  }
}

function renderImage(carBuffer, tintRgb) {
  const W = 600;
  const H = 1067;

  // slate background as a real image (sharp composite has a quirk with raw buffers)
  const slatePath = path.join(__dirname, '.ba-slate.png');
  const tintPath = path.join(__dirname, '.ba-tint.png');
  sharp({ create: { width: W, height: H, channels: 3, background: { r: 11, g: 14, b: 38 } } })
    .png().toFileSync(slatePath);
  sharp({ create: { width: W, height: H, channels: 3, background: { r: tintRgb[0], g: tintRgb[1], b: tintRgb[2] } } })
    .png().toFileSync(tintPath);

  const withBg = sharp(carBuffer)
    .composite([{ input: slatePath, blend: 'over' }])
    .toBufferSync();

  const tinted = sharp(withBg)
    .composite([{ input: tintPath, blend: 'multiply' }])
    .toBufferSync();

  const meta = sharp(carBuffer).metadataSync();
  const scale = Math.min(W / meta.width, H / meta.height);
  const fitW = Math.round(meta.width * scale);
  const fitH = Math.round(meta.height * scale);
  const x = Math.round((W - fitW) / 2);
  const y = Math.round((H - fitH) / 2);
  const scaled = sharp(tinted)
    .extract({ left: x, top: y, width: fitW, height: fitH })
    .resize(W, H, { fit: 'fill', kernel: 'lanczos3' })
    .toBufferSync();

  const labelY = 48;
  const beforeLabel = 'BEFORE';
  const beforeX = Math.round((W - beforeLabel.length * 9 * 10) / 2);
  drawText(scaled, beforeLabel, beforeX, labelY, 10);
  const afterLabel = 'AFTER';
  const afterX = Math.round((W - afterLabel.length * 9 * 10) / 2);
  drawText(scaled, afterLabel, afterX, labelY, 10);

  return scaled;
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });

  const carBuffer = fs.readFileSync(SRC);
  const beforeRgb = [0x5A, 0x55, 0x48]; // muddy brown-gray
  const afterRgb = [0xEC, 0xC0, 0xB8]; // warm clean shine

  for (let i = 1; i <= 6; i++) {
    const before = renderImage(carBuffer, beforeRgb);
    const after = renderImage(carBuffer, afterRgb);
    await sharp(before).jpeg({ quality: 80 }).toFile(path.join(OUT, `ba-${i}-before.jpg`));
    await sharp(after).jpeg({ quality: 80 }).toFile(path.join(OUT, `ba-${i}-after.jpg`));
    console.log(`Wrote ba-${i}`);
  }
  console.log('Done');
})();
